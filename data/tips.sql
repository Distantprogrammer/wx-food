<p>【爆(bào)】利用热镬（锅）热油，攒入适量调好的汁酱或汤水，使镬中的小件食物快速致熟又赋入香气的烹调方法。</p>
<p>【炸(zhá)】古写作“煠(zhá)”，最常用的烹调方法之一；指将食物放入大量的热油中致熟至脆的烹调手法。</p>
<p>【烚(xiá)】古写作“煠”，利用大量的沸水将肉质较韧的食物在炉火上炊软炊熟的加工方法。</p>
