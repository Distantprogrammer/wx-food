<p>这是整个流程的核心步骤。推荐水温为温水到热水（约 40–50°C），热水能有效降低油脂黏度，大幅提高去污效率。如果家里有可调温水龙头，建议直接调到合适温度。</p>
<p>标准手洗步骤：</p>
<ol>
<li>打开水龙头，或在洗碗盆中准备一盆温水。</li>
<li>海绵上挤少量洗涤剂（绿豆到黄豆大小，约 1–2ml 即可），打出泡沫。</li>
<li>按「外→内、柄→头、边缘→中心」的顺序刷洗：
<ul>
<li><strong>碗</strong>：先刷外壁，再刷内壁，重点刷碗底内侧</li>
<li><strong>盘</strong>：盘面、盘沿、盘底</li>
<li><strong>筷勺</strong>：筷头和勺头是重点污染区域</li>
<li><strong>锅</strong>：锅底、锅壁、锅沿，别忘了锅外侧飞溅的油渍</li>
</ul>
</li>
<li>遇到顽固污渍，先用海绵粗糙面局部加压擦洗，不要一上来就上钢丝球。</li>
<li>案板和刀具：
<ul>
<li>生肉案板：洗涤剂刷洗后，可用热水烫洗。条件允许时定期消毒。</li>
<li>刀具：刀刃朝远离自己的方向刷，避免割伤。</li>
</ul>
</li>
</ol>
<p>洗涤剂不是越多越干净。用太多只会增加后面漂洗的工作量，而且残留在餐具上本身也不好。</p>
<h3>4. 漂洗：去除洗涤剂</h3>
<p>清洗之后，需要用清水把洗涤剂和已溶解的污垢彻底冲掉。</p>
<p>操作：</p>
<ol>
<li>在流动清水下彻底冲洗每件餐具，直到满足以下条件：
<ul>
<li>无泡沫</li>
<li>手指摸上去无滑腻感</li>
<li>表面水膜均匀（如果油没洗干净，水会聚成珠状而不是均匀铺开）</li>
</ul>
</li>
<li>杯口、碗底凹槽、锅柄接缝处容易残留洗涤剂，多冲几秒。</li>
<li>若使用洗碗盆静态漂洗，建议至少换水一次，最后再用流动水过一遍。</li>
</ol>
