<p>注意：</p>
<ul>
<li>沥水时尽量<strong>倒扣或侧立</strong>，避免碗盘凹面积水。</li>
<li>如果抹布本身已经有异味或潮湿发黏，先把抹布洗干净，再用它擦餐具。</li>
<li>不要用刚擦过灶台的布去擦碗。</li>
</ul>
<h3>7. 收纳</h3>
<p>确认餐具已经干燥后，放回橱柜或碗架。</p>
<p>几条基本规则：</p>
<ol>
<li><strong>未干不收</strong>：潮湿的餐具放进柜子会滋生细菌和异味。</li>
<li>碗盘叠放前确认底部干净，不要把脏底部压在下面碗的内壁上。</li>
<li>筷子、勺子、叉子头朝上摆放，或按家中沥水篮设计方向摆放，保持通风。</li>
<li>处理过生食的刀具和案板与日常餐具分区存放。</li>
</ol>
<h2>推荐清洗顺序</h2>
<p>如果一次洗完全套，建议按以下顺序：</p>
<pre><code class="language-text">1. 玻璃杯 / 杯子
2. 筷子、勺子、叉子
3. 盘子、碗
4. 锅铲、汤勺等炊具
5. 炒锅 / 煮锅（重油）
6. 生食案板与刀具（最后，并单独清洗水槽）
7. 冲洗水槽与龙头把手（收尾）
</code></pre>
<p>道理是：污染从低到高推进，避免后面的重油污反过来弄脏前面已经洗好的东西。</p>
<h2>不同材质的餐具处理</h2>
<p>现代厨房中各种材质的锅具和餐具混用是常态，但不同材质的清洗方式差异很大。用错方法轻则损伤器具，重则产生健康隐患。</p>
<h3>不粘锅</h3>
<ul>
<li>使用海绵软面 + 中性洗涤剂，轻柔擦洗即可。</li>
<li><strong>禁止使用钢丝球、硬质铲刮涂层</strong>，否则涂层会被破坏，锅也就废了。</li>
<li>洗后擦干，避免长时间积水。</li>
</ul>
<h3>铸铁锅 / 碳钢锅</h3>
<ul>
<li>尽量不用或少用洗涤剂，以保护锅表面的油膜。</li>
<li>用热水 + 刷子去除残渣即可。</li>
<li>洗完后擦干，小火烘干，再薄涂一层食用油防锈。</li>
</ul>
<h3>木质案板 / 木铲</h3>
<ul>
<li>快速清洗，不要长时间浸泡，否则木头会开裂变形。</li>
<li>洗后竖立晾干。</li>
<li>定期可擦食用油保养（案板）。</li>
</ul>
<h3>筷子</h3>
<ul>
<li>重点洗接触食物的一端（筷头）。</li>
<li>竹木筷容易积水开裂，洗后务必晾干。</li>
<li>出现严重发霉或开裂时直接更换，不要勉强继续使用。</li>
</ul>
<h3>洗碗机</h3>
<p>洗碗机是现代厨房中最能提升效率的工具之一，但它不是「把碗扔进去就行」的万能机器，仍然需要人工配合才能发挥最佳效果：</p>
<ol>
<li>先刮掉大块残渣（骨头、菜叶等），否则容易堵塞滤网和喷淋孔。</li>
<li>按洗碗机说明书摆放餐具，碗口朝下、盘子侧立，注意不要遮挡喷淋臂的旋转。</li>
<li>选择合适的程序——重油用强力或高温档，轻污日常用快洗或节能档即可。</li>
<li>洗完后打开检查，重点看碗底凹槽和杯口内侧，如有未洗净的，手洗补一下。</li>
<li>定期清理洗碗机滤网与密封圈，防止异味和霉变。建议每 1–2 周清理滤网，每月用专用清洁剂空洗一次。</li>
</ol>
<h3>空气炸锅</h3>
<p>空气炸锅的炸篮和底盘是主要清洗对象，很多人只擦一下就放回去，时间长了油垢会碳化，影响加热效果和食品安全。</p>
<ul>
<li>每次使用后，等机器冷却后取出炸篮和底盘，用温水 + 洗涤剂 + 海绵清洗。</li>
<li>炸篮网格缝隙容易卡住食物残渣，可用旧牙刷或小刷子辅助清理。</li>
<li><strong>不要用钢丝球刷炸篮</strong>——大多数炸篮有不粘涂层，用钢丝球刷会破坏涂层，导致后续使用粘连和涂层脱落。</li>
<li>机身内壁如有油污飞溅，用湿抹布擦拭即可，<strong>不要把机身整体浸入水中</strong>。</li>
<li>加热管（顶部）如沾有油渍，冷却后用湿布轻擦。长期不清理的油渍在高温下会冒烟甚至产生有害物质。</li>
</ul>
<h3>电饭锅</h3>
<p>电饭锅内胆大多有不粘涂层，清洗时需要注意保护涂层。很多人忽略了蒸汽阀和锅盖内侧的清洗。</p>
<ul>
<li>内胆使用海绵软面 + 洗涤剂清洗，<strong>禁止钢丝球</strong>。涂层一旦划伤脱落，米饭会粘锅，脱落的涂层碎片也会混入食物。</li>
<li>锅盖内侧、蒸汽孔、密封圈是容易被忽略的部位——淀粉蒸汽会在这些地方凝结成黏糊状残留，时间长了会发酸发臭。建议每次使用后擦拭锅盖内侧，定期拆下密封圈清洗。</li>
<li>锅体外壳只能用湿布擦拭，<strong>不要浸水</strong>，避免损坏电路。</li>
</ul>
<h3>高压力锅 / 电压力锅</h3>
<p>高压力锅的清洗重点不在锅体本身，而在密封圈、排气阀和锅盖等安全相关部件。这些部件如果清洗不到位，不仅影响卫生，还可能影响密封性能，存在安全隐患。</p>
<ul>
<li><strong>密封圈</strong>：每次使用后取下，用温水 + 洗涤剂清洗。密封圈的凹槽里容易藏食物残渣和油垢，需要仔细擦洗。洗后晾干再装回。密封圈老化（变硬、变形、有裂纹）后应及时更换。</li>
<li><strong>排气阀 / 限压阀</strong>：拆下后用清水冲洗，确保阀孔通畅无堵塞。如果阀孔被食物残渣堵住，下次使用时可能导致泄压异常。</li>
<li><strong>锅盖</strong>：内侧及锅盖边缘凹槽容易积聚油污和食物残留，需要擦洗干净。</li>
<li><strong>内胆</strong>：与普通不锈钢锅或不粘锅清洗方法相同，根据内胆材质选择工具。</li>
</ul>
<h3>烤箱</h3>
<p>烤箱的烤盘、烤架和内壁都需要定期清洗。很多人只洗烤盘，忽略了烤架和内壁，时间长了油垢碳化后会产生烟味，甚至影响食物风味。</p>
<ul>
<li><strong>烤盘</strong>：趁温热时（注意别烫手）用洗涤剂 + 海绵清洗，冷却后油垢会凝固变难清理。有顽固烧结物时，用热水浸泡 15–30 分钟再刷。铺锡纸或烘焙纸可以大幅减少烤盘清洗的难度。</li>
<li><strong>烤架</strong>：网格状烤架的缝隙是清洗难点，可放在水槽中用热水 + 洗涤剂浸泡后用刷子刷洗。</li>
<li><strong>内壁</strong>：冷却后用湿布 + 少量洗涤剂擦拭。如果油渍已经碳化变黑，可以用小苏打 + 水调成糊状涂在污渍上，放置 1–2 小时后再擦。不要用钢丝球刮烤箱内壁，容易损伤表面涂层。</li>
<li>有些烤箱带自清洁功能（高温热解），可以按说明书使用，但事后仍需擦掉残留的灰烬。</li>
</ul>
<h3>微波炉</h3>
<p>微波炉内壁和转盘容易被食物溅出的汤汁、油脂弄脏，很多人不清理，时间长了会有异味，加热时旧的食物残渣还会反复受热产生焦味。</p>
<ul>
<li><strong>转盘</strong>：取出后和普通玻璃/瓷器一样清洗即可。</li>
<li><strong>内壁</strong>：用湿布 + 少量洗涤剂擦拭。如果有干结的食物飞溅，可以在微波炉里放一碗水加几片柠檬，中火加热 3–5 分钟，利用蒸汽软化污渍后再擦，会轻松很多。</li>
<li><strong>门封条</strong>：门框边缘的密封条是容易被忽略的死角，油渍和碎屑会积在缝隙里，应定期用湿布擦拭。</li>
<li><strong>不要用带有金属成分的清洁工具</strong>擦拭微波炉内壁，以免损伤内壁涂层。</li>
</ul>
<h3>蒸锅 / 蒸屉</h3>
<p>蒸锅和蒸屉使用后最常见的问题是水垢和淀粉残留。</p>
<ul>
<li><strong>不锈钢蒸屉</strong>：洗涤剂 + 海绵正常清洗即可。蒸屉孔容易卡住面食残渣（如馒头、包子底部），需要及时清理，否则干结后很难去除。</li>
<li><strong>竹制蒸笼</strong>：不要用洗涤剂，用热水 + 刷子刷洗即可。竹子会吸附洗涤剂的味道，下次蒸东西时气味会渗入食物。洗后务必通风晾干，否则容易发霉。发霉的竹蒸笼应丢弃。</li>
<li><strong>蒸锅锅体</strong>：底部容易积水垢（白色结晶），可用白醋浸泡 10–20 分钟后刷洗。</li>
</ul>
<h3>锅铲 / 汤勺 / 漏勺</h3>
<p>这些工具每天都在用，但不同材质的清洗方式有区别：</p>
<ul>
<li><strong>不锈钢</strong>：最耐操，可以用钢丝球刷，不怕划伤。注意清洗勺柄连接处的缝隙，油污容易藏在那里。</li>
<li><strong>硅胶</strong>：用海绵 + 洗涤剂清洗即可。硅胶耐高温但容易吸附颜色和气味（尤其是咖喱、番茄酱），如果变色严重可用小苏打水浸泡。不要用钢丝球刷硅胶表面，会留下划痕并更容易藏污。</li>
<li><strong>木质</strong>：和木铲、木案板一样，快洗快干不浸泡。详见前面「木质案板 / 木铲」部分。</li>
</ul>
<h3>削皮刀</h3>
<p>削皮刀的刀刃和卡槽之间缝隙极小，菜皮纤维和淀粉很容易卡在里面。很多人用完只是在水下冲一下，其实并没有清干净。</p>
<ul>
<li>用旧牙刷顺着刀刃方向刷洗缝隙（注意方向，避免割伤）。</li>
<li>洗后甩干水分，放在通风处晾干。不锈钢削皮刀如果长期潮湿不晾干，刀刃也会生锈变钝。</li>
</ul>
<h3>热水壶 / 电热水壶</h3>
<p>热水壶的主要问题不是油污，而是水垢。</p>
<ul>
<li><strong>水垢清除</strong>：倒入白醋或柠檬酸（约 1–2 汤匙），加满水，烧开后关火浸泡 30–60 分钟，倒掉后用清水冲洗 2–3 遍。水质较硬的地区建议每 1–2 周除垢一次。</li>
<li>不要用钢丝球刷壶内壁，容易划伤不锈钢表面，划痕会让水垢更容易附着。</li>
<li>壶嘴和壶盖内侧也会积水垢，注意一并清理。</li>
</ul>
<h2>常见问题与踩坑</h2>
<p>以下是洗碗过程中最常见的错误做法和认知误区，按类型整理。每一条都附带了具体后果——知道「为什么不能这样做」，才能真正避开这些坑。</p>
<h3>清洗习惯类</h3>
<ul>
<li><strong>只冲不刷</strong>：光用水冲是去不掉油膜的。油脂不溶于水，必须靠洗涤剂的表面活性剂将油脂乳化，再配合海绵的物理摩擦才能去除。只冲不刷的结果是碗表面看着干净，实际上还有一层薄油膜，摸起来滑腻，下次盛饭时食物会沾上变质油脂的异味。</li>
<li><strong>洗涤剂放太多</strong>：泡沫多并不等于洗得干净，洗涤剂超过一定浓度后去污效果不会继续提升。放太多的后果是漂洗阶段很难冲干净，残留的洗涤剂会被下次吃饭时一并吃进去。长期摄入洗涤剂残留虽然不会立刻中毒，但对肠胃黏膜有刺激，也没有必要冒这个风险。</li>
<li><strong>只洗内壁不洗外壁和底部</strong>：很多人洗碗时只刷碗里面，忽略外壁和碗底。碗盘叠放时，上面碗的底部直接接触下面碗的内壁——如果底部是脏的，等于下面那只碗白洗了。</li>
<li><strong>漂洗不彻底就晾干</strong>：碗上还残留着洗涤剂的泡沫就拿出去沥水。晾干后洗涤剂会在碗面形成一层干燥的薄膜，下次使用时随食物进入体内。判断方法很简单：用手指摸一下，如果还有滑腻感就没冲干净。</li>
<li><strong>隔夜不处理</strong>：淀粉和蛋白质残渣在室温下放一晚上会干结得非常牢固，第二天要花好几倍的力气去刷。更重要的是，夏天室温下食物残渣 2–4 小时就开始大量繁殖细菌，隔夜的脏碗基本就是一个培养皿。如果碗里有肉类残渣，还会招来蟑螂和果蝇。</li>
</ul>
<h3>工具使用类</h3>
<ul>
<li><strong>钢丝球刷不粘锅</strong>：钢丝球会划伤不粘涂层（通常是特氟龙），涂层一旦破损就会持续脱落。破损的不粘锅不仅失去不粘功能，脱落的涂层碎片还会混入食物中。涂层破损后锅体直接暴露，也容易粘锅糊锅。正确做法是只用海绵软面擦洗不粘锅。</li>
<li><strong>用脏抹布或臭海绵擦碗</strong>：海绵和抹布长期潮湿不晾干，本身就是细菌和霉菌的温床。用发臭的海绵去"洗"碗，相当于把细菌抹了一遍。抹布也是同理——用刚擦过灶台油污的布去擦碗，只是把脏东西搬了个地方。建议海绵每次用完挤干通风，抹布定期高温清洗或更换。</li>
<li><strong>用硬质工具刮搪瓷/陶瓷涂层</strong>：搪瓷锅和有陶瓷涂层的锅具表面比较脆，用金属铲或钢丝球用力刮会崩瓷或刮花。搪瓷崩掉后露出底层金属，不仅影响加热均匀性，金属暴露后还容易生锈。</li>
<li><strong>洗碗时水龙头一直开着大水</strong>：全程开着水龙头冲，一次洗碗下来可能浪费几十升水。更好的做法是：先关水用海绵和洗涤剂把所有餐具都擦一遍，然后统一开水漂洗。</li>
</ul>
<h3>材质损伤类</h3>
<ul>
<li><strong>铸铁锅/碳钢锅长时间浸泡</strong>：铸铁和碳钢没有防锈涂层（或靠一层油膜防锈），长时间泡在水里会迅速生锈。一旦生锈不仅难看，锈蚀严重时还需要重新开锅养锅。正确做法是洗完立刻擦干，小火烘干后薄涂一层食用油。</li>
<li><strong>铸铁锅/碳钢锅用大量洗涤剂</strong>：洗涤剂会把锅表面好不容易养出来的油膜洗掉，下次使用时会严重粘锅。铸铁锅和碳钢锅日常清洗只需要热水 + 刷子，顽固残渣可以加粗盐摩擦。</li>
<li><strong>热锅直接冲冷水</strong>：炒完菜的锅温度很高，直接冲冷水会造成剧烈的热胀冷缩。不锈钢锅可能变形，铸铁锅甚至可能开裂。锅里有残余热油时冲冷水还会导致油水飞溅，可能烫伤。应等锅稍微冷却后再清洗。</li>
<li><strong>木质案板/木铲长时间泡水</strong>：木头吸水后膨胀，晾干后收缩，反复几次就会开裂变形。木质案板有裂缝后，缝隙中容易藏匿食物残渣和细菌，很难清洗干净。正确做法是快洗快干，竖立晾放。</li>
</ul>
<h3>卫生隐患类</h3>
<ul>
<li><strong>湿碗直接放进柜子</strong>：没晾干就放进封闭的橱柜，相当于给细菌和霉菌提供了温暖潮湿的理想环境。几天之后碗上可能出现霉点或异味，整个柜子里的餐具都可能受到影响。</li>
<li><strong>生熟混洗不分</strong>：切过生肉、生鱼的案板和刀具如果直接放到洗碗水里和其他碗筷一起洗，生肉上可能携带的沙门氏菌、大肠杆菌等就会通过水传播到其他餐具上。正确做法是生食工具最后单独清洗，必要时用热水烫洗或消毒。</li>
<li><strong>沥水架长期不清理</strong>：沥水架底部的接水盘如果不定期倒水和清洗，积水会发臭、长霉，沥在架子上的碗反而被底部蒸发上来的脏水二次污染。建议每周清洗一次沥水架和接水盘。</li>
<li><strong>筷子笼底部积水</strong>：筷子头朝下插在筷子笼里，笼底如果没有排水孔或者长期不清理，底部会积水发霉。筷子头是接触食物的部分，泡在脏水里等于每次吃饭都在用发霉的筷子。要么选有排水孔的筷子笼，要么筷头朝上放。</li>
<li><strong>发霉的竹木筷继续使用</strong>：竹木筷出现黑色霉斑后，霉菌已经深入木质纤维，普通清洗无法去除。部分霉菌（如黄曲霉）会产生强致癌物质。发霉、开裂的竹木筷应直接丢弃更换。</li>
</ul>
<h3>其他容易忽略的坑</h3>
<ul>
<li><strong>洗碗机里残渣不刮就放</strong>：以为洗碗机什么都能洗。大块残渣（骨头、菜叶、饭粒）会堵塞滤网和喷淋孔，导致洗碗机清洗效果下降，严重时还会损坏排水泵。放进洗碗机前至少要先刮掉明显的固体残渣。</li>
<li><strong>洗碗机长期不清理</strong>：洗碗机内部的滤网、密封圈、喷淋臂如果长期不清理，会积累油污和霉菌，不仅洗出来的碗有异味，还可能导致洗碗机本身成为污染源。建议每 1–2 周清理一次滤网，每月用洗碗机专用清洁剂运行一次空洗程序。</li>
<li><strong>残渣直接冲下水道</strong>：饭粒、面条、菜叶等淀粉类残渣冲进下水道后容易膨胀结团，时间长了会堵塞管道。油脂冲进去后会在管壁凝结，加速堵塞。正确做法是先把固体残渣刮进垃圾桶，水槽出水口加一个滤网拦截漏网的碎渣。</li>
<li><strong>洗涤剂和含氯漂白剂混用</strong>：部分人会在洗碗水里同时加洗涤剂和 84 消毒液（含氯漂白剂）想要"双重杀菌"，但两者混合可能产生有害气体，刺激呼吸道。如果需要消毒，应在正常清洗、漂洗完毕后，单独用消毒液浸泡，最后再用清水冲净。</li>
</ul>
<h2>小结</h2>
