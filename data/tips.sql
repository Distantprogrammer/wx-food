<p class="markdown-alert-title">Warning</p>
<p><strong>油锅未冷却时不要直接冲冷水</strong>。热胀冷缩可能导致锅体变形，油遇冷水也可能飞溅烫伤。
<strong>铸铁锅、碳钢锅</strong>不要长时间浸泡，否则容易生锈。洗完应立即擦干并薄涂一层油。</p>
