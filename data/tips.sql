<li>可以选择足够大的食品密封袋腌渍。此时是封口腌渍，一般时间很长，例如隔夜腌渍，或腌渍不易入味的排骨等。常见 4 小时-隔夜。此时用料要稍微减少，防止成菜口感太重太咸</li>
</ul>
<h2>常用的腌渍用料</h2>
<ul>
<li>生抽：调酱香且带有咸味的底味。可用于几乎所有肉类</li>
<li>老抽：咸味并不强烈，但是易于染色。用于调底色和增香。一般不应大量使用防止产生豆腥味。可用于几乎所有红肉类（较少用），猪肝等可以多加</li>
<li>食盐：咸味但炒制后不带有酱香味。可用于所有肉类</li>
<li>白（砂）糖：调甜味（量大），也可以为肉增加鲜嫩的口感（量少）。可用于所有禽畜类肉类，但鱼类和海鲜并不常用。</li>
<li>红糖：调甜味和红糖特有的口感，口味比白糖略重。可用于几乎所有肉类（一般肉色较深或者成菜颜色较深）</li>
<li>蚝油：增加鲜、咸、甜的口味。一般用于红肉</li>
<li>白醋/米醋：增加酸的口味。较少使用</li>
<li>陈醋/香醋：不仅带有酸的口味，还能为菜品增香增色。香醋比较适合深色鱼类（尤其是烤鱼）</li>
<li>料酒：去腥增香。可用于几乎所有肉类。但是使用需要注意：
<ul>
<li>料酒本身的味道很浓，很容易掩盖食材本身的香味，对于腥味不浓郁的食材，可以考虑不用料酒来去腥。例如：牛肉，鱼肉和鸡肉。</li>
<li>对于鸡肉，可以用白酒去代替料酒。</li>
<li>对于牛肉，可以用姜葱水代替料酒。</li>
<li>对于白色鱼肉，只需要清洗干净血丝和粘膜就不会有什么腥味了，建议不加料酒。</li>
</ul>
</li>
<li>黄酒：去腥增香，效果比料酒更好，香味比料酒更复杂。一般用于白肉类。红肉也可用，但是效果与料酒相当。</li>
<li>五香粉/十三香：为肉类增加香味，是最简单的复合香料。五香粉仅仅增加香味，十三香的香味比较独特，有辨识度。用此类香料腌渍应该控制用量。可用于几乎所有肉类，但鱼类和海鲜不常用</li>
<li>辣椒粉：辣椒粉分为很多种。不谈辣椒的种类，从研磨精细度划分有辣椒粉/辣椒面，辣椒碎等。除了为肉类增加辣味，还能为成菜配色。用辣椒腌渍的菜品应该避免辣椒过量。可用于几乎所有需要辣味底味的肉类，但烹调时间应该略加控制，防止辣椒味道变苦，或者颜色变深</li>
<li>孜然粉、小茴香粉：一般用磨粉作为腌料，不用颗粒，这样可以使肉类更容易入味。可用于几乎所有红肉和鸡肉</li>
<li>X 椒粉：为肉类增加辛、辣、香、呛的口味。使用应该适量，防止盖过其他口味
<ul>
<li>黑胡椒粉：口味辛、辣。可用于几乎所有红肉</li>
<li>白胡椒粉：口味辛、香。比黑胡椒略弱，突出香味。可用于几乎所有肉类</li>
<li>花椒粉：口味辛、呛。有花椒特殊的香味，比较有辨识度。可用于几乎所有肉类</li>
</ul>
</li>
<li>豆瓣酱：为肉类增加豆类的酱香和咸味、辣味。可用于几乎所有红肉类</li>
<li>葱姜蒜：葱姜去腥增香，去除异味；蒜增加辛香味。葱可根据需要切段或者切片；姜一般切片，有些场景需要去皮；蒜可切片或切碎。葱姜不想出现在成菜中，或者口味需要较轻，可以将葱姜块放于有极少量清水的碗里挤压出汁，用葱姜水腌渍肉类。蒜一般不直接加入。可用于所有肉类</li>
<li>海鲜酱、虾酱等：为肉类增加鲜、咸味。海鲜酱口味偏甜，虾酱口味偏重。可用于几乎所有肉类，但使用场景不多</li>
<li>豆豉：为肉类增加发酵豆类的香味和咸味。可用于几乎所有红肉类，但是使用的并不多</li>
<li>生粉：即为淀粉。生粉是上浆的重要腌料。上浆越厚，或者需要口感越滑嫩，需要的生粉越多。可用于几乎所有肉类。<code>生粉可作为简易的油炸外衣使用（一般根据需要还需加入面粉等），此时一般不在腌渍时加入</code>
<ul>
<li>玉米淀粉、土豆淀粉：粘性一般最大</li>
<li>红薯淀粉：粘性略低</li>
</ul>
</li>
<li>油：在腌渍时加入适量油进行油封，可以锁住水分和风味。如使用开口容器腌渍，且时间较长（例如在碗里），油封能极大程度保证肉质不变干或变柴。可用于几乎所有肉类。油封后炒制应略微减少底油，油炸则没有区别</li>
</ul>
<h2>几种较为通用的腌渍公式</h2>
<ul>
<li>牛肉：使用适量生抽，少量料酒，少量白砂糖腌渍。根据口味选用食盐（补充咸味），蚝油和极少量海鲜酱（蚝油牛肉），五香粉/十三香（洋葱炒牛肉）。慎用葱姜</li>
