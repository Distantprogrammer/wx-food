<h2>选购油</h2>
<p>在选购油之前，需要了解一些脂肪酸的基础知识</p>
<h3>脂肪酸的分类</h3>
<p>脂肪酸分为：</p>
<ul>
<li>饱和脂肪酸 （尽量避免）</li>
<li>不饱和脂肪酸
<ul>
<li>顺式脂肪酸</li>
<li>反式脂肪酸 （尤其注意避免）</li>
<li>多不饱和脂肪酸</li>
<li>单不饱和脂肪酸</li>
</ul>
</li>
</ul>
<p>饱和脂肪酸在室温下会呈固态，而不饱和脂肪酸在室温下会呈液态。</p>
<h3>避免的脂肪酸</h3>
<p>其中，<strong>饱和脂肪酸</strong>和<strong>反式脂肪酸</strong>一般是被认为不健康的。</p>
<p>饱和脂肪酸会增加肥胖、高胆固醇、心脏病的风险。</p>
<p>研究表明，长期过量食用氢化加工产生的反式脂肪酸可引起人体血脂代谢异常，从而增加心血管疾病发生的风险。也有研究显示可能会增加糖尿病、肥胖等慢性疾病的患病风险。</p>
<p>世界卫生组织建议：为增进心血管健康，应尽量控制膳食中的反式脂肪酸，最大摄取量不超过总能量的 1%。也就是说，如果按一个成年人平均每天摄入能量 2000 千卡来算，则每天摄入反式脂肪酸不应超过 2.2 克。</p>
<p>GB 28050-2011 规定，食品配料含有或生产过程中使用了氢化和（或）部分氢化油脂时，在营养成分表中还应标示出反式脂肪（酸）的含量。</p>
<h3>食品中的的反式脂肪酸</h3>
<p>根据相关调查，焙烤食品（糕点、饼干、面包等）、调味品、油炸食品的反式脂肪酸平均含量在 0.30~0.50 g/100g 之间。</p>
<p>因此不必太过担心——日常食品中的反式脂肪酸并不足以危害健康。但以防万一，在选购零食时，不妨关注营养成分表中标注的 <code>反式脂肪（酸）</code> 含量。</p>
<h3>烹饪中的反式脂肪酸</h3>
<p>据 2021 年调查显示，我国植物油的反式脂肪酸平均含量为 0.86 g/100g，无需太过担心。</p>
<p>要额外注意的反式脂肪酸来源是烹饪过程：</p>
<p>植物油中往往含有较高比例的多不饱和脂肪酸，热稳定性比较差，容易在高温下转化成反式脂肪。</p>
<p>因此，在不同场景下，我们需要合理选择油品，并尽可能减少油品的加热时间。</p>
