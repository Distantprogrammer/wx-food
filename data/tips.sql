<p>每件餐具过一遍：</p>
<ul>
<li><strong>看</strong>：迎光观察是否有油膜反光</li>
<li><strong>摸</strong>：指腹轻触内壁，看是否发黏</li>
<li><strong>闻</strong>：凑近闻是否有酸味或洗涤剂味</li>
</ul>
<p>没通过的，回到第 3 步局部重洗。不要带着没洗干净的地方直接去晾干。</p>
<h3>6. 干燥</h3>
<p>洗干净不等于可以直接用——湿润的环境是细菌繁殖的温床。很多人洗完碗就觉得任务完成了，但如果不干燥就收纳，前面的努力可能白费。</p>
<p>可选做法：</p>
