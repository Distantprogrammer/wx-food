                <h1>如何洗碗</h1>
<h2>21世纪的洗碗</h2>
<p>洗碗是厨房工作中看起来最简单的工作。随着现代化厨房工具日益复杂化，“洗碗”早已不局限于其字面意义，但很多人对洗碗的认知却仍停留在“用毛巾擦洗碗具”的“古法”阶段，有的家庭甚至由于长期不科学的洗碗方式埋下健康隐患（如致癌物）。为了让大家掌握科学、高效、现代化的洗碗方法，本指南将详细介绍洗碗的流程、注意事项和避坑整理。</p>
<h2>洗碗的目的</h2>
<p>不管你用的是传统手洗还是洗碗机，最终目的只有一个：让餐具回到<strong>可以安全再次使用</strong>的状态。具体来说，需要同时满足以下几点：</p>
<ol>
<li><strong>看起来干净</strong>：表面无油膜、水渍、菜渣、指纹。</li>
<li><strong>摸起来干净</strong>：用手指划一下碗底、勺柄、杯口内侧，如果没有粘滞感就说明干净了。</li>
<li><strong>闻起来干净</strong>：无酸败油味、无刺鼻洗涤剂味。</li>
<li><strong>干燥可用</strong>：沥干或擦干后无明显积水，收纳时不潮湿。</li>
<li><strong>没有交叉污染</strong>：处理过生肉的工具没有污染到已洗净的餐具。</li>
</ol>
<p>以上 5 条全部满足，才算洗干净了。</p>
<h2>需要准备的工具</h2>
<p>现代厨房的餐具材质多样（不粘涂层、铸铁、搪瓷、木质、不锈钢……），不同材质需要不同的清洗工具，选错工具本身就是一个常见的坑。厨房准备中已默认存在洗涤相关工具，洗碗时建议保证下列物品可用：</p>
<pre><code class="language-text">热水（优先）、冷水、洗碗槽、洗碗盆（可选）、洗碗海绵/百洁布
洗涤剂、钢丝球（仅限不锈钢锅具，禁用于不粘锅/涂层）
沥水架、干净抹布或厨房纸巾、手套（可选）
洗碗机（可选，详见后文）
</code></pre>
<h3>工具使用要点</h3>
<ul>
<li><strong>海绵/百洁布</strong>：日常碗盘首选。使用后挤干并通风晾放，避免海绵本身发霉变臭。</li>
<li><strong>钢丝球</strong>：只用于铁锅、不锈钢锅等硬质无涂层表面。<strong>禁止</strong>用于不粘锅、陶瓷涂层、精致瓷器，否则会破坏涂层。</li>
<li><strong>抹布</strong>：擦干餐具的抹布必须与擦灶台、擦地面的抹布分开，混用等于白洗。</li>
<li><strong>洗碗机</strong>：若有洗碗机，可跳过手洗主流程，但仍需完成刮渣预处理和洗后收纳。详见后文「洗碗机」部分。</li>
</ul>
<h2>整体流程</h2>
<p>很多人洗碗只有「打洗涤剂→冲水」两步，这远远不够。一套科学的洗碗流程应该包含以下环节：</p>
<pre><code class="language-text">收集分类 → 刮渣浸泡 → 清洗去污 → 漂洗去洗涤剂 → 检查 → 干燥 → 收纳
</code></pre>
<p>每一步都有不可替代的作用，跳过任何一步都可能留下隐患。下面逐步说明。</p>
<h2>详细步骤</h2>
<h3>1. 收集与分类</h3>
<p>饭后先把散落在各处的碗、盘、筷、勺、锅、案板等集中到水槽旁边，按污染程度分好顺序。</p>
<p>建议按以下顺序清洗（从轻到重）：</p>
<ol>
<li><strong>轻污</strong>：玻璃杯、水杯、筷子、勺子</li>
<li><strong>中污</strong>：盛菜盘、饭碗</li>
<li><strong>重污</strong>：炒菜锅、油炸锅、烤盘、粘了蛋液的容器</li>
<li><strong>高风险</strong>：处理过生肉、生鱼的案板与刀具（建议最后单独处理）</li>
</ol>
<p>为什么要分类：先洗轻污的，水和海绵都比较干净，不会把重油污带到杯子上；生食工具最后单独洗，避免把病原体带到已洗净的餐具上。</p>
<h3>2. 刮渣与浸泡</h3>
<p>这一步是很多人会跳过的，但它直接决定了后续清洗的难度。提前把顽固的残渣处理掉，正式洗的时候就不用反复刷，既省力又省水。</p>
<p>操作：</p>
<ol>
<li>用餐巾纸或锅铲刮去大块残渣，倒入厨余垃圾桶。<strong>不要直接冲进下水道</strong>，容易堵塞。</li>
<li>以下情况需要浸泡：
<ul>
<li>干结的饭粒、淀粉糊</li>
<li>蛋白类凝固物（蛋液、牛奶残留）</li>
<li>焦锅、糊底</li>
</ul>
</li>
<li>浸泡方法：
<ul>
<li><strong>普通油污、饭粒</strong>：热水浸泡 5–15 分钟</li>
<li><strong>焦糊锅底</strong>：热水 + 少量洗涤剂浸泡，或先加水烧开再关火焖 10–20 分钟</li>
<li><strong>不锈钢上的茶渍、水垢</strong>：可用少量白醋浸泡后刷洗（不要与漂白类产品混用）</li>
</ul>
</li>
</ol>
